function report = p2_validate_future_job(job,cfg)
%P2_VALIDATE_FUTURE_JOB Validate a draft config against its workload manifest.
% Deliberately cannot authorize or execute a formal job.
    fields={'N','n_sc','cp','taps','source_seed','source_samples','quadrature_order', ...
        'snr_grid','strategy_p','strategy_names','controls','num_channels','num_frames','future_split','predict','diagnose'};
    assert(isstruct(job) && isscalar(job) && isstruct(cfg) && isscalar(cfg) && ...
        all(isfield(job,[fields,{'job_id','purpose','case_manifest'}])) && ...
        all(isfield(cfg,[fields,{'mode','purpose','power_file'}])), ...
        'futurejob:MissingFields','Draft job or configuration is missing fields.');
    assert(strcmp(cfg.mode,'draft_only') && isempty(cfg.power_file), ...
        'futurejob:InvalidMode','Draft-only fixed-amplitude configuration required.');
    assert(strcmp(job.purpose,cfg.purpose),'futurejob:Mismatch','Purpose differs.');
    for k=1:numel(fields)
        assert(isequaln(job.(fields{k}),cfg.(fields{k})), ...
            'futurejob:Mismatch','Draft configuration differs from job manifest.');
    end
    assert(isnumeric(cfg.N) && isscalar(cfg.N) && cfg.N>=4 && isfinite(cfg.N) && mod(log2(cfg.N),1)==0 && ...
        isnumeric(cfg.n_sc) && isscalar(cfg.n_sc) && isfinite(cfg.n_sc) && cfg.n_sc==fix(cfg.n_sc) && cfg.n_sc>=3 && ...
        isnumeric(cfg.taps) && isscalar(cfg.taps) && isfinite(cfg.taps) && cfg.taps==fix(cfg.taps) && cfg.taps>=1 && ...
        isnumeric(cfg.cp) && isscalar(cfg.cp) && isfinite(cfg.cp) && cfg.cp==fix(cfg.cp) && cfg.cp>=cfg.taps-1 && cfg.cp<cfg.n_sc && ...
        isnumeric(cfg.snr_grid) && isvector(cfg.snr_grid) && ~isempty(cfg.snr_grid) && all(isfinite(cfg.snr_grid)) && ...
        numel(unique(cfg.snr_grid))==numel(cfg.snr_grid), ...
        'futurejob:InvalidPhysical','Invalid code, OFDM or reference SNR configuration.');
    cases=p2_future_draft_cases(cfg.strategy_p,cfg.strategy_names,cfg.controls);
    assert(isequaln(cases,job.case_manifest),'futurejob:CasesMismatch','Case list differs from manifest.');
    work=struct('job_id',job.job_id,'purpose',job.purpose,'split',cfg.future_split, ...
        'num_channels',cfg.num_channels,'num_snr',numel(cfg.snr_grid), ...
        'num_cases',numel(cases),'num_frames',cfg.num_frames,'case_manifest',cases);
    budget=p2_preflight_future_workload(work,31*15*256*8191);
    report=struct('job_id',job.job_id,'case_frames',budget.total_case_frames, ...
        'case_count',numel(cases),'status','draft_only_not_authorized');
end

