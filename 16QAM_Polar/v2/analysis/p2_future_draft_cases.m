function cases = p2_future_draft_cases(strategy_p,strategy_names,controls)
%P2_FUTURE_DRAFT_CASES Expand proposed 16QAM candidates for budget checking.
% Draft only. No experiment, asset validation or scientific acceptance.
    assert(isnumeric(strategy_p) && isreal(strategy_p) && size(strategy_p,2)==3 && ...
        ~isempty(strategy_p) && all(ismember(strategy_p(:),[.1,.3,.5])) && ...
        iscellstr(strategy_names) && numel(strategy_names)==size(strategy_p,1) && ...
        numel(unique(strategy_names))==numel(strategy_names) && all(~cellfun(@isempty,strategy_names)), ...
        'draftcases:InvalidStrategies','Three-group p rows and unique names are required.');
    assert(iscellstr(controls) && ~isempty(controls) && strcmp(controls{1},'shaped') && ...
        all(ismember(controls,{'shaped','random_s','donor_s'})) && ...
        numel(unique(controls))==numel(controls),'draftcases:InvalidControls', ...
        'Unique supported controls with shaped first are required.');
    cases=struct('id',{},'p',{},'kind',{});
    for i=1:size(strategy_p,1)
        for j=1:numel(controls)
            if all(strategy_p(i,:)==.5) && j>1, continue; end
            if strcmp(strategy_names{i},'bad_channel_energy_only') && ~strcmp(controls{j},'shaped'), continue; end
            cases(end+1)=struct('id',[strategy_names{i} '_' controls{j}], ...
                'p',strategy_p(i,:),'kind',controls{j}); %#ok<AGROW>
        end
    end
    assert(numel(unique({cases.id}))==numel(cases),'draftcases:DuplicateIDs','Expanded case IDs must be unique.');
end
