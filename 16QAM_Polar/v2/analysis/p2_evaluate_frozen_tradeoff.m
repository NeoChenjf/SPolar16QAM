function summary = p2_evaluate_frozen_tradeoff(frozen, T, baseline_ids)
%P2_EVALUATE_FROZEN_TRADEOFF Compare frozen training selection to baselines.
% Test rows must be independently generated and aligned by channel. This
% function does not optimize, calculate intervals or guarantee RF/DC gains.
    assert(isstruct(frozen) && isfield(frozen,'status') && strcmp(frozen.status,'selected') && ...
        isfield(frozen,'selected_case') && ~isempty(frozen.selected_case) && ...
        all(isfield(frozen,{'training_seed','reference_snr_db','beta2','beta4','max_ber','min_goodput'})), ...
        'tradeofftest:InvalidFrozen','A selected frozen training result is required.');
    required={'purpose','seed','channel','snr_db','case_id','control','frames','ber','goodput_cp', ...
        'rx_envelope_m2_l4','rx_envelope_m4_l4','noise_complex_time_power'};
    assert(istable(T) && ~isempty(T) && all(ismember(required,T.Properties.VariableNames)), ...
        'tradeofftest:InvalidTable','Required independent test columns are missing.');
    assert(all(ismember(T.purpose,{'test_seen','strategy_test'})) && numel(unique(T.purpose))==1 && all(strcmp(T.control,'shaped')) && ...
        numel(unique(T.seed))==1 && all(T.seed~=frozen.training_seed) && ...
        all(T.snr_db==frozen.reference_snr_db), ...
        'tradeofftest:InvalidRole','Test role, seed or reference SNR is invalid.');
    assert(iscellstr(baseline_ids) && ~isempty(baseline_ids) && ...
        numel(unique(baseline_ids))==numel(baseline_ids), ...
        'tradeofftest:InvalidBaseline','Baseline IDs must be distinct character vectors.');
    numbers=[T.ber,T.goodput_cp,T.rx_envelope_m2_l4,T.rx_envelope_m4_l4,T.frames,T.noise_complex_time_power];
    assert(all(isfinite(numbers(:))) && all(T.ber>=0 & T.ber<=1) && ...
        all(T.goodput_cp>=0 & T.goodput_cp<=1) && all(T.rx_envelope_m2_l4>=0) && ...
        all(T.rx_envelope_m4_l4>=0) && all(T.frames>0 & T.frames==fix(T.frames)) && ...
        all(T.noise_complex_time_power>0), ...
        'tradeofftest:InvalidMetrics','Test metrics must be finite and valid.');
    chosen=T(strcmp(T.case_id,frozen.selected_case),:);
    assert(~isempty(chosen) && numel(unique(chosen.channel))==height(chosen), ...
        'tradeofftest:InvalidSelected','Selected candidate rows missing or duplicated.');
    channels=sort(chosen.channel); [~,ix]=ismember(channels,chosen.channel); chosen=chosen(ix,:);
    out=cell(numel(baseline_ids),6);
    for k=1:numel(baseline_ids)
        base=T(strcmp(T.case_id,baseline_ids{k}),:); [found,ix]=ismember(channels,base.channel);
        assert(height(base)==height(chosen) && all(found) && numel(unique(base.channel))==height(base), ...
            'tradeofftest:Unpaired','Baseline must cover the same distinct channels.');
        base=base(ix,:);
        assert(isequal(chosen.frames,base.frames) && ...
            isequal(chosen.noise_complex_time_power,base.noise_complex_time_power), ...
            'tradeofftest:Unpaired','Frame budgets and noise power must match.');
        ja=frozen.beta2*chosen.rx_envelope_m2_l4+frozen.beta4*chosen.rx_envelope_m4_l4;
        jb=frozen.beta2*base.rx_envelope_m2_l4+frozen.beta4*base.rx_envelope_m4_l4;
        assert(all(isfinite(ja)) && all(isfinite(jb)), ...
            'tradeofftest:InvalidMetrics','Proxy overflow.');
        out(k,:)={baseline_ids{k},height(chosen),mean(chosen.ber-base.ber), ...
            mean(chosen.goodput_cp-base.goodput_cp),mean(ja-jb), ...
            sum(chosen.ber<=frozen.max_ber & chosen.goodput_cp>=frozen.min_goodput)};
    end
    summary=cell2table(out,'VariableNames',{'baseline','channels','delta_ber','delta_goodput', ...
        'delta_proxy','selected_channels_meeting_thresholds'});
end
