function p2_validate_common_raw_metrics(run_dir, T)
%P2_VALIDATE_COMMON_RAW_METRICS Recompute table quantities from raw records.
    loaded=load(fullfile(run_dir,'params.mat'),'cfg'); cfg=loaded.cfg;
    required={'purpose','seed','channel','snr_db','case_id','frames','error_count','info_bits', ...
        'ber','rate_cp','goodput_cp','rx_envelope_m2_l4','rx_envelope_m4_l4','noise_complex_time_power'};
    assert(istable(T) && ~isempty(T) && all(ismember(required,T.Properties.VariableNames)), ...
        'rawmetrics:InvalidTable','Required raw-linked metrics are missing.');
    assert(all(T.seed==cfg.seed) && all(strcmp(T.purpose,cfg.purpose)), ...
        'rawmetrics:InvalidRole','Rows do not match saved run role or seed.');
    for i=1:height(T)
        index=find(cfg.snr_grid==T.snr_db(i));
        assert(isscalar(index),'rawmetrics:InvalidSNR','SNR must be unique in run.');
        filename=fullfile(run_dir,sprintf('raw_c%d_s%d_%s.mat',T.channel(i),index,T.case_id{i}));
        assert(isfile(filename),'rawmetrics:MissingRaw','Required raw file is missing.');
        loaded=load(filename,'artifact'); a=loaded.artifact; rec=[a.records{:}];
        errors=sum(a.stream_errors(:)); bits=sum(a.info_counts(:));
        K=bits/cfg.num_frames; rate=K/(4*cfg.n_sc*a.layout.n_symbols)*cfg.n_sc/(cfg.n_sc+cfg.cp);
        assert(bits>0 && T.frames(i)==cfg.num_frames && numel(rec)==T.frames(i) && ...
            abs(rate-T.rate_cp(i))<1e-12 && errors==T.error_count(i) && bits==T.info_bits(i) && ...
            abs(errors/bits-T.ber(i))<1e-12 && abs(rate*(1-T.ber(i))-T.goodput_cp(i))<1e-12 && ...
            abs(mean([rec.rx_m2_l4])-T.rx_envelope_m2_l4(i))<1e-12 && ...
            abs(mean([rec.rx_m4_l4])-T.rx_envelope_m4_l4(i))<1e-12 && ...
            abs(a.noise_complex_time_power-T.noise_complex_time_power(i))<= ...
                1e-12*max(abs(a.noise_complex_time_power),realmin), ...
            'rawmetrics:Mismatch','Table metrics do not match raw data.');
    end
end
