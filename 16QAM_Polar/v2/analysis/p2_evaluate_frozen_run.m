function summary = p2_evaluate_frozen_run(frozen, run_dir, baseline_ids)
%P2_EVALUATE_FROZEN_RUN Audit raw pairing before independent strategy comparison.
    loaded=load(fullfile(run_dir,'params.mat'),'cfg'); cfg=loaded.cfg;
    assert(any(strcmp(cfg.purpose,{'test_seen','strategy_test'})), ...
        'frozenrun:InvalidRole','Only independent strategy test roles are supported.');
    p2_audit_common_pairing(run_dir);
    T=readtable(fullfile(run_dir,'repetitions.csv'));
    required={'purpose','seed','channel','snr_db','case_id','control','frames','error_count', ...
        'info_bits','ber','rate_cp','goodput_cp','rx_envelope_m2_l4','rx_envelope_m4_l4','noise_complex_time_power'};
    assert(all(ismember(required,T.Properties.VariableNames)), ...
        'frozenrun:MissingColumns','Missing raw-linked evaluation columns.');
    chosen=unique([{frozen.selected_case},baseline_ids(:)']);
    T=T(strcmp(T.control,'shaped') & ismember(T.case_id,chosen),:);
    assert(~isempty(T) && all(T.seed==cfg.seed) && all(strcmp(T.purpose,cfg.purpose)), ...
        'frozenrun:InvalidRows','Rows do not match the saved run role and seed.');
    for i=1:height(T)
        index=find(cfg.snr_grid==T.snr_db(i));
        assert(isscalar(index),'frozenrun:InvalidRows','Reference SNR is not unique in run.');
        filename=fullfile(run_dir,sprintf('raw_c%d_s%d_%s.mat',T.channel(i),index,T.case_id{i}));
        raw=load(filename,'artifact'); a=raw.artifact; r=[a.records{:}];
        errors=sum(a.stream_errors(:)); bits=sum(a.info_counts(:));
        K=sum(a.info_counts(:))/cfg.num_frames;
        rate=K/(4*cfg.n_sc*a.layout.n_symbols)*cfg.n_sc/(cfg.n_sc+cfg.cp);
        assert(bits>0 && T.frames(i)==cfg.num_frames && numel(r)==T.frames(i) && ...
            abs(rate-T.rate_cp(i))<1e-12 && errors==T.error_count(i) && bits==T.info_bits(i) && ...
            abs(errors/bits-T.ber(i))<1e-12 && abs(T.rate_cp(i)*(1-T.ber(i))-T.goodput_cp(i))<1e-12 && ...
            abs(mean([r.rx_m2_l4])-T.rx_envelope_m2_l4(i))<1e-12 && ...
            abs(mean([r.rx_m4_l4])-T.rx_envelope_m4_l4(i))<1e-12 && ...
            abs(a.noise_complex_time_power-T.noise_complex_time_power(i)) <= ...
                1e-12*max(abs(a.noise_complex_time_power),realmin), ...
            'frozenrun:RawMismatch','Metrics do not agree with saved raw records.');
    end
    summary=p2_evaluate_frozen_tradeoff(frozen,T,baseline_ids);
end
